package app

import (
	"io"
	"math"
	"regexp"
	"strconv"
	"strings"
	"time"
)

// Every slicer writes down what a print will use, and none of them agree on
// where or how. OrcaSlicer (and Bambu Studio, its parent) puts a header block
// at the top; PrusaSlicer and SuperSlicer put totals and the whole config at
// the bottom; Cura puts ;TIME: and ;Filament used: at the top in metres. So the
// file is read at both ends — never the middle, which is the hundred megabytes
// of moves — and whatever is found is taken.

// GcodeMeta is what a sliced file says about itself. Zero means not stated.
type GcodeMeta struct {
	Grams    float64
	Length   float64 // mm of filament
	Seconds  float64 // the slicer's estimate
	Material string  // as the slicer wrote it: "PETG", "PLA"
	Colour   string  // "#RRGGBB" when the slicer gives one
	Slicer   string
	Diameter float64
}

func (m GcodeMeta) Known() bool { return m.Grams > 0 || m.Length > 0 || m.Seconds > 0 }

// Duration is the estimate as a duration, for the pages.
func (m GcodeMeta) Duration() time.Duration { return time.Duration(m.Seconds * float64(time.Second)) }

// GramsFor fills in a weight from length when the slicer gave only length,
// which Cura does. Weight is length times the filament's cross-section times
// the plastic's density.
func (m GcodeMeta) GramsFor(density float64) float64 {
	if m.Grams > 0 {
		return m.Grams
	}
	if m.Length <= 0 || density <= 0 {
		return 0
	}
	d := m.Diameter
	if d <= 0 {
		d = 1.75
	}
	area := math.Pi * (d / 2) * (d / 2)     // mm²
	return m.Length * area * density / 1000 // mm³ × g/cm³ ÷ 1000
}

// metaWindow is how much of each end is read. Orca's header and Prusa's
// footer config both fit comfortably; Prusa's config alone runs to ~40 KB.
const metaWindow = 160 << 10

// ReadGcodeMeta reads the start and end of a G-code file.
func ReadGcodeMeta(r io.ReaderAt, size int64) GcodeMeta {
	read := func(off, n int64) string {
		if off < 0 {
			n += off
			off = 0
		}
		if n <= 0 {
			return ""
		}
		buf := make([]byte, n)
		got, _ := r.ReadAt(buf, off)
		return string(buf[:got])
	}
	head := read(0, metaWindow)
	tail := ""
	if size > metaWindow {
		tail = read(size-metaWindow, metaWindow)
	}
	return ParseGcodeMeta(head + "\n" + tail)
}

var (
	reKV = regexp.MustCompile(`(?m)^\s*;\s*([^:=\n]+?)\s*[:=]\s*(.+?)\s*$`)
	// "; generated by OrcaSlicer 2.1.1 on 2026-10-03 at 14:02:11" has its first
	// colon inside the time, so the slicer's name gets a pattern of its own
	// rather than going through the key-value split.
	reGenerated = regexp.MustCompile(`(?mi)^\s*;\s*generated (?:by|with)\s+([A-Za-z][\w.-]*)`)
	// "1d 2h 3m 4s", "2h 5m", "45m 10s" — the estimate as slicers print it.
	reDur = regexp.MustCompile(`(?:(\d+)d)?\s*(?:(\d+)h)?\s*(?:(\d+)m)?\s*(?:(\d+)s)?`)
)

// ParseGcodeMeta reads the comment lines. Exposed separately so a test can
// hand it a header without building a file.
func ParseGcodeMeta(text string) GcodeMeta {
	var m GcodeMeta
	if g := reGenerated.FindStringSubmatch(text); g != nil {
		m.Slicer = strings.Split(g[1], "_")[0] // "Cura_SteamEngine" -> "Cura"
	}
	// A total overrides a per-extruder figure, but not another total: the
	// first total in the file is the slicer's own summary.
	haveTotal := false
	for _, kv := range reKV.FindAllStringSubmatch(text, -1) {
		key := strings.ToLower(strings.TrimSpace(kv[1]))
		val := strings.TrimSpace(kv[2])

		switch {
		// Weight. Orca: "total filament weight [g]"; Prusa: "total filament
		// used [g]" and per-extruder "filament used [g]". The total wins when
		// both are there.
		case key == "total filament weight [g]", key == "total filament used [g]":
			if g := sumList(val); g > 0 && !haveTotal {
				m.Grams, haveTotal = g, true
			}
		case key == "filament used [g]":
			if m.Grams == 0 {
				m.Grams = sumList(val)
			}

		// Length. Cura says metres with a unit; the others say millimetres.
		case key == "filament used":
			if strings.HasSuffix(strings.ToLower(val), "m") && !strings.HasSuffix(strings.ToLower(val), "mm") {
				m.Length = sumList(strings.TrimSuffix(strings.TrimSuffix(val, "m"), "M")) * 1000
			}
		case key == "total filament length [mm]", key == "filament used [mm]":
			if m.Length == 0 {
				m.Length = sumList(val)
			}

		// Time.
		case key == "time": // Cura: ;TIME:4983
			if s, err := strconv.ParseFloat(val, 64); err == nil {
				m.Seconds = s
			}
		case strings.HasPrefix(key, "estimated printing time"):
			// Prusa writes normal and silent modes; normal comes first and wins.
			if m.Seconds == 0 {
				m.Seconds = parseSlicerDuration(val)
			}
		case key == "model printing time":
			// Orca puts two estimates on one line:
			// "model printing time: 1h 2m 3s; total estimated time: 1h 5m 10s"
			if i := strings.Index(val, "total estimated time:"); i >= 0 {
				m.Seconds = parseSlicerDuration(val[i+len("total estimated time:"):])
			} else if m.Seconds == 0 {
				m.Seconds = parseSlicerDuration(val)
			}

		case key == "filament_type", key == "filament type":
			if m.Material == "" {
				m.Material = firstListItem(val)
			}
		case key == "filament_colour", key == "filament_color", key == "extruder_colour":
			if c := normaliseHex(firstListItem(val)); c != "" && (m.Colour == "" || key != "extruder_colour") {
				m.Colour = c
			}
		case key == "filament_diameter":
			if d, err := strconv.ParseFloat(firstListItem(val), 64); err == nil && d > 0 {
				m.Diameter = d
			}
		}
	}
	return m
}

// sumList adds a comma- or semicolon-separated list of numbers, which is how
// slicers report one figure per extruder. A single number is a list of one.
func sumList(s string) float64 {
	total := 0.0
	for _, part := range strings.FieldsFunc(s, func(r rune) bool { return r == ',' || r == ';' }) {
		if v, err := strconv.ParseFloat(strings.TrimSpace(part), 64); err == nil && v > 0 {
			total += v
		}
	}
	return total
}

func firstListItem(s string) string {
	if i := strings.IndexAny(s, ";,"); i >= 0 {
		s = s[:i]
	}
	return strings.Trim(strings.TrimSpace(s), `"`)
}

func parseSlicerDuration(s string) float64 {
	s = strings.ToLower(strings.TrimSpace(s))
	if v, err := strconv.ParseFloat(s, 64); err == nil {
		return v
	}
	match := reDur.FindStringSubmatch(s)
	if match == nil || match[0] == "" {
		return 0
	}
	units := []float64{86400, 3600, 60, 1}
	total := 0.0
	for i, u := range units {
		if match[i+1] != "" {
			n, _ := strconv.ParseFloat(match[i+1], 64)
			total += n * u
		}
	}
	return total
}
